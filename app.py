def build_user_prompt(question: str) -> str:
    return f"""
국민건강보험공단 업무와 관련하여 민원인이 말한 문의 내용:
{question}

위 문의에 국민건강보험공단 상담사가 민원인에게 직접 설명하는 것처럼 답변하세요.

현재 다음 정보는 조회할 수 없습니다:
- 개인 자격정보
- 보험료 부과 및 납부 내역
- 소득과 재산 자료
- 체납정보와 환급금
- 건강검진 대상 여부와 검진 결과
- 만성질환 관리사업 참여 대상 여부
- 공단 내부 상담 스크립트와 내부 업무자료

조회가 필요한 내용은 확정하지 말고,
민원인이 확인해야 할 사항과 다음 처리 방향을 친절하게 안내하세요.

건강검진 결과, 증상 또는 만성질환과 관련된 질문이라면
진단이나 치료 지시를 하지 말고 공단 업무 범위의 안내와 의료기관 확인 필요성을 구분해서 설명하세요.
"""


@app.get("/")
def index():
    return render_template("index.html")


@app.get("/health")
def health():
    return jsonify(
        {
            "ok": True,
            "api_key_configured": bool(API_KEY),
            "model": MODEL_NAME,
        }
    )


@app.post("/chat")
def chat():
    if client is None:
        return (
            jsonify(
                {
                    "ok": False,
                    "error": (
                        "Gemini API 키가 설정되지 않았습니다. "
                        "Render 환경변수 또는 .env 파일을 확인해주세요."
                    ),
                }
            ),
            500,
        )

    data = request.get_json(silent=True) or {}
    question = str(data.get("question", "")).strip()

    if not question:
        return jsonify({"ok": False, "error": "문의 내용을 입력해주세요."}), 400

    if len(question) > 1000:
        return (
            jsonify(
                {
                    "ok": False,
                    "error": "문의 내용은 1,000자 이내로 입력해주세요.",
                }
            ),
            400,
        )

    try:
        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=build_user_prompt(question),
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT,
                temperature=0.35,
                max_output_tokens=700,
            ),
        )

        answer = (response.text or "").strip()

        if not answer:
            raise ValueError("Gemini가 빈 답변을 반환했습니다.")

        return jsonify(
            {
                "ok": True,
                "answer": answer,
            }
        )

    except Exception as exc:
        print(f"[Gemini error] {type(exc).__name__}: {exc}")

        return (
            jsonify(
                {
                    "ok": False,
                    "error": (
                        "상담 답변을 준비하지 못했습니다. "
                        "잠시 후 다시 시도해주세요."
                    ),
                    "detail": str(exc) if app.debug else "",
                }
            ),
            500,
        )


if __name__ == "__main__":
    app.run(
        host="0.0.0.0",
        port=int(os.getenv("PORT", "5000")),
        debug=True,
    )